// 띄어 읽기: 문장 끝·쉼표 뒤에 쉼, 그리고 절이 끝나는 연결어미 뒤에 짧은 쉼.
// Chirp 3 HD는 SSML 대신 markup의 [pause] 표시를 받는다. 잘못 쉬는 것이 안 쉬는 것보다 거슬리므로 애매하면 붙여 읽는다:
// '제자·어머니'처럼 명사 끝 글자는 어미로 보지 않고, 인용(-다고·-라고), '-고 있다'·'쓸고 지나가는' 같은 이어진 용언,
// '듣고 행하는 사람'·'의롭고 경건한'처럼 꾸밈말 안의 -고, '에서·께서·가운데서·제게서' 뒤, '-려고', '-면 되다·좋다'는 쉬지 않는다
const ENDING = /(?:[시하되오가르들지서차나보]자|[으하되보오가이시]니|고|서|며|면|는데|지만)$/;
export const pauses = t => t
  .replace(/([.?!])\s+/g, '$1 [pause] ')
  .replace(/,\s*/g, ', [pause short] ')
  .replace(/(\S+)\s(?=(\S+)(?:\s(\S+))?)/g, (m, w, n1, n2 = '') => {
    if (!ENDING.test(w) || /(?:에서|께서|[데게]서|[다라냐자려]고)$/.test(w) || /[,\]]$|^\[/.test(w + n1)) return m;
    if (/^(?:있|없|싶|계|말았|나서|지나|가|갔|오|왔|와|다니|다닌|보|주|버리|놓|두)/.test(n1)) return m;
    if (/면$/.test(w) && /^(?:되|됩|좋|안)/.test(n1)) return m;
    if (/고$/.test(w) && [n1, n2].some(x => /[는은던온운한인을]$/.test(x) && !/^(?:그|이|저)/.test(x))) return m;
    return `${w} [pause short] `;
  });
